/* Synthetic-obstructions schema preview — the ONLY place mock obstruction
 * data renders. Design rules (research: REPORT-ux-proposal.md, P2):
 *  - a click-through gate EVERY visit (no storage: staff turn over,
 *    warnings must not expire with a cookie);
 *  - the map render itself is watermarked, because badges don't survive
 *    screenshots — any crop of this map self-identifies as synthetic;
 *  - never linked from a primary map surface; reachable from Sources. */
(function () {
  const B = window.BSD;
  B.initPage("obstructions-preview.html");
  const app = document.getElementById("app");

  app.innerHTML = `
    <h1>Bike-lane obstructions — synthetic demo ${B.badgeHTML("mock")}</h1>
    <div class="notice">
      <strong>Nothing on this page is real.</strong> Every point below is generated
      demonstration data. It exists to preview the obstruction-report schema this site is
      ready to accept once a real source exists (a data-sharing conversation with
      <a href="${B.LINKS.blu}" target="_blank" rel="noopener">Bike Lane Uprising</a> is the
      goal). Real obstructions in the real world go to
      <a href="${B.LINKS.blu}" target="_blank" rel="noopener">Bike Lane Uprising</a> or
      <a href="${B.LINKS.threeOneOne}" target="_blank" rel="noopener">311</a>.
    </div>
    <div class="card" id="gateCard">
      <h2>Before you look</h2>
      <p>This preview renders <strong>invented</strong> obstruction reports on a map of real
      Chicago streets. It must never be cited, screenshotted into a meeting packet, or shared
      as evidence — the map is watermarked for exactly that reason. This warning appears on
      every visit; it never remembers you.</p>
      <p><button class="btn primary" id="gateBtn">I understand — show the synthetic demo</button></p>
    </div>
    <div id="demoWrap" style="display:none">
      <div class="synthetic-frame">
        <div id="previewMap" style="height:420px"></div>
        <div class="synthetic-watermark" aria-hidden="true"></div>
      </div>
      <p class="muted prov-line" style="margin-top:0.4rem">SYNTHETIC DEMONSTRATION DATA — not real
      reports. Schema docs on the <a href="contributing.html">Downloads &amp; Docs page</a>;
      provenance on the <a href="sources.html#src-obstructions">Sources page</a>.</p>
      <div id="demoStats"></div>
    </div>`;

  document.getElementById("gateBtn").addEventListener("click", () => {
    document.getElementById("gateCard").style.display = "none";
    const wrap = document.getElementById("demoWrap");
    wrap.style.display = "";
    buildMap();
  });

  function buildMap() {
    const map = L.map("previewMap", { zoomSnap: 0.5 }).setView([41.87, -87.66], 11);
    L.tileLayer("https://{s}.basemaps.cartocdn.com/light_all/{z}/{x}/{y}{r}.png", {
      attribution: '&copy; <a href="https://www.openstreetmap.org/copyright">OpenStreetMap</a> contributors &copy; <a href="https://carto.com/attributions">CARTO</a>',
      subdomains: "abcd", maxZoom: 19,
    }).addTo(map);

    B.loadJSON("data/obstructions_mock.geojson").then(fc => {
      const feats = fc.features || [];
      L.layerGroup(feats.map(f => {
        const p = f.properties;
        const [lng, lat] = f.geometry.coordinates;
        return L.circleMarker([lat, lng], {
          radius: 4, color: "#b91c1c", weight: 1, dashArray: "2,2", fillOpacity: 0.35,
        }).bindPopup(
          `<strong>SYNTHETIC — not a real report</strong><br>` +
          `Type: ${B.esc(p.obstruction_type)}<br>When: ${B.esc((p.occurred_at || "").replace("T", " "))}`);
      })).addTo(map);

      const byType = {};
      feats.forEach(f => {
        const t = f.properties.obstruction_type || "other";
        byType[t] = (byType[t] || 0) + 1;
      });
      document.getElementById("demoStats").innerHTML =
        `<div class="card"><h2>What the schema captures ${B.badgeHTML("mock")}</h2>
        <p>${B.fmt(feats.length)} synthetic points, generated by
        <code>pipeline/make_mock_obstructions.py</code>. Category enum is a placeholder,
        swappable the day real data exists — nothing downstream re-architects.</p>
        <dl>${Object.entries(byType).sort((a, z) => z[1] - a[1]).map(([t, n]) =>
          `<dt>${B.esc(t)}</dt><dd>${B.fmt(n)}</dd>`).join("")}</dl></div>`;
    }).catch(err => {
      document.getElementById("demoStats").innerHTML =
        `<div class="notice">Could not load the synthetic file: ${B.esc(err.message)}</div>`;
    });
  }
})();
