/* Shared runtime for every screen: nav, data-quality badges, disclaimers,
 * data loading, CSV export, URL state. Exposed as window.BSD.
 * UI code MUST use BSD.badge()/noticeHTML() so tier labeling stays uniform —
 * "data quality is always visible" is a hard product constraint. */
(function () {
  const TIER_INFO = {
    real: "Real data from the named public source (raw counts, provisional for recent months).",
    proxy: "Proxy signal: correlated with the phenomenon but biased (self-reporting or sensor placement). Read direction, not magnitude.",
    mock: "MOCK demonstration data — synthetic, generated by this project. Not real reports.",
    crowdsourced: "Crowdsourced/manually curated — unverified, coverage depends on contributors.",
    stub: "No data yet — placeholder layer showing where a future source plugs in.",
    derived: "Computed from real underlying data (e.g. a normalized rate, trend, or automated "
      + "topic tag) rather than sourced directly — read as an analytical signal, not a raw fact.",
  };

  // One-line plain-language versions of the tiers, used by the tier-explainer
  // modal that opens when any badge is tapped.
  const TIER_PLAIN = {
    real: "from official records",
    proxy: "a related signal, not a direct measure",
    derived: "calculated by us from real data",
    mock: "fake demo data — not real reports",
    crowdsourced: "volunteer-reported, unverified",
    stub: "no data yet — a placeholder for a future source",
  };

  const DISCLAIMERS = {
    dooring: "Dooring undercount: dooring crashes are structurally excluded from official " +
      "“reportable” crash records unless damage/injury thresholds are met. Any crash density " +
      "shown here understates dooring risk, especially on painted-lane corridors.",
    directional: "How to read this: these are directional, visual signals — density bands and " +
      "overlap, not statistical analysis. Nothing here is normalized for how many people ride " +
      "each street unless explicitly labeled. Use it to spot patterns worth acting on, not to prove causation.",
    normalization: "Raw counts overrepresent busy corridors: no public cyclist-volume data is " +
      "joined yet, so a popular street can look worse than a dangerous quiet one.",
  };

  const NAV = [
    ["index.html", "Map"],
    ["network.html", "Network"],
    ["findings.html", "Findings"],
    ["table.html", "Explore Data"],
    ["sources.html", "Sources"],
    ["action.html", "Take Action"],
    ["contributing.html", "Downloads & Docs"],
  ];

  const FACILITY_COLORS = {
    protected: "#0b6e4f", buffered: "#2f9e6e", painted: "#f59e0b",
    greenway: "#6d28d9", sharrow: "#b45309", trail: "#0369a1", other: "#64748b",
  };
  const FACILITY_LABELS = {
    protected: "Protected lane", buffered: "Buffered lane", painted: "Painted lane",
    greenway: "Neighborhood greenway", sharrow: "Shared-lane marking", trail: "Off-street trail",
    other: "Other/unknown",
  };
  const SEVERITY_ORDER = ["fatal", "incapacitating", "non_incapacitating",
    "reported_not_evident", "none", "unknown"];
  const SEVERITY_LABELS = {
    fatal: "Fatal", incapacitating: "Incapacitating injury",
    non_incapacitating: "Non-incapacitating injury", reported_not_evident: "Reported, not evident",
    none: "No indication of injury", unknown: "Unknown",
  };
  const SEVERITY_COLORS = {
    fatal: "#7f1d1d", incapacitating: "#dc2626", non_incapacitating: "#f59e0b",
    reported_not_evident: "#64748b", none: "#94a3b8", unknown: "#94a3b8",
  };

  const LINKS = {
    threeOneOne: "https://311.chicago.gov",
    blu: "https://www.bikelaneuprising.com",
    aldermanLookup: "https://www.chicago.gov/city/en/about/wards.html",
  };

  function esc(s) {
    return String(s == null ? "" : s).replace(/[&<>"']/g,
      c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
  }

  // Badges are tappable, never hover-only: a <button> with data-tier that the
  // delegated document click handler (wired in initPage) opens the explainer for.
  function badgeHTML(tier) {
    const t = TIER_INFO[tier] ? tier : "stub";
    return `<button type="button" class="badge tier-${t}" data-tier="${t}">` +
      `${t === "stub" ? "no data yet" : t}</button>`;
  }
  function badge(tier) {
    const tmp = document.createElement("div");
    tmp.innerHTML = badgeHTML(tier);
    return tmp.firstChild;
  }

  // Shared modal: one lazily-created <dialog class="modal"> reused by every
  // caller. Focus returns to the invoking element on close.
  let _modal = null;
  function openModal({ title, bodyHTML }) {
    const opener = document.activeElement;
    if (!_modal) {
      _modal = document.createElement("dialog");
      _modal.className = "modal";
      document.body.appendChild(_modal);
    }
    _modal.innerHTML =
      `<div class="modal-head"><strong>${esc(title)}</strong>` +
      `<button type="button" class="btn modal-close" aria-label="Close">×</button></div>` +
      `<div class="modal-body">${bodyHTML}</div>`;
    _modal.querySelector(".modal-close").addEventListener("click", () => _modal.close());
    _modal.addEventListener("close", function onClose() {
      _modal.removeEventListener("close", onClose);
      if (opener && opener.focus) opener.focus();
    });
    _modal.showModal();
    return _modal;
  }

  function noticeHTML(kind) {
    const cls = kind === "dooring" ? "dooring" : kind === "directional" ? "directional" : "";
    return `<div class="notice ${cls}">${esc(DISCLAIMERS[kind] || kind)}</div>`;
  }

  async function loadJSON(path) {
    const resp = await fetch(path);
    if (!resp.ok) throw new Error(`fetch ${path}: ${resp.status}`);
    return resp.json();
  }

  function fmt(n) {
    return n == null ? "—" : Number(n).toLocaleString("en-US");
  }

  const TREND_LABELS = {
    improving: "Improving",
    worsening: "Worsening",
    flat: "Flat",
    insufficient_data: "Insufficient data",
  };

  const TREND_ARROWS = {
    improving: "▼",
    worsening: "▲",
    flat: "→",
    insufficient_data: "·",
  };

  function trendHTML(trend) {
    if (trend.direction === "insufficient_data" || trend.pct_change == null) {
      return `<span style="color: var(--ink-soft)">· Insufficient data</span>`;
    }

    const arrow = TREND_ARROWS[trend.direction];
    const label = TREND_LABELS[trend.direction];
    const color = trend.direction === "worsening" ? "var(--sev-incap)"
      : trend.direction === "improving" ? "var(--accent)"
      : "var(--ink-soft)";
    const pct = trend.pct_change;
    const pctStr = pct % 1 === 0 ? pct.toFixed(0) : pct.toFixed(1);
    const sign = pct > 0 ? "+" : "";
    const text = `${arrow} ${label} (${sign}${pctStr}% vs prior 12 mo)`;
    return `<span style="color: ${color}">${esc(text)}</span>`;
  }

  function scoreColor(score) {
    if (score == null) return "#e2e8f0";
    if (score >= 80) return "#991b1b";
    if (score >= 60) return "#dc2626";
    if (score >= 40) return "#f59e0b";
    if (score >= 20) return "#fbbf24";
    return "#fde68a";
  }

  function money(n) {
    if (n == null) return "—";
    const rounded = Math.round(n);
    return "$" + rounded.toLocaleString("en-US");
  }

  function qs() {
    return new URLSearchParams(location.search);
  }
  function setParams(obj) {
    const p = new URLSearchParams(location.search);
    for (const [k, v] of Object.entries(obj)) {
      if (v === null || v === undefined || v === "" || v === false) p.delete(k);
      else p.set(k, v === true ? "1" : v);
    }
    history.replaceState(null, "", `${location.pathname}?${p}`);
  }

  function downloadCSV(filename, rows, columns) {
    const cols = columns || Object.keys(rows[0] || {});
    const cell = v => {
      const s = v == null ? "" : String(v);
      return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
    };
    const csv = [cols.join(",")]
      .concat(rows.map(r => cols.map(c => cell(r[c])).join(",")))
      .join("\n");
    const a = document.createElement("a");
    a.href = URL.createObjectURL(new Blob([csv], { type: "text/csv" }));
    a.download = filename;
    a.click();
    URL.revokeObjectURL(a.href);
  }

  function initPage(activeHref) {
    if (!document.querySelector("link[rel='icon']")) {
      const icon = document.createElement("link");
      icon.rel = "icon";
      icon.href = "data:image/svg+xml," + encodeURIComponent(
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16"><circle cx="4" cy="11" r="3.2" fill="none" stroke="%230b6e4f" stroke-width="1.6"/><circle cx="12" cy="11" r="3.2" fill="none" stroke="%230b6e4f" stroke-width="1.6"/><path d="M4 11 6.5 5h3L12 11M6.5 5 8 11" fill="none" stroke="%230b6e4f" stroke-width="1.4"/></svg>');
      document.head.append(icon);
    }
    const header = document.createElement("header");
    header.className = "site-header";
    header.innerHTML =
      `<a class="brand" href="index.html">On Your Left!<small>Chicago bike safety, on the record</small></a>` +
      `<nav class="site-nav">` +
      NAV.map(([href, label]) =>
        `<a href="${href}"${href === activeHref ? ' class="active"' : ""}>${label}</a>`).join("") +
      `</nav>`;
    document.body.prepend(header);

    const footer = document.createElement("footer");
    footer.className = "site-footer";
    footer.innerHTML =
      `Directional signals, not statistical analysis. This tool does not collect reports — ` +
      `use <a href="${LINKS.threeOneOne}" target="_blank" rel="noopener">311</a> or ` +
      `<a href="${LINKS.blu}" target="_blank" rel="noopener">Bike Lane Uprising</a>. ` +
      `Open source & open data — see the <a href="contributing.html">Downloads & Docs page</a>. ` +
      `Every number is labeled — real · proxy · derived · mock · crowdsourced — ` +
      `tap any label to see what it means.`;
    document.body.append(footer);

    // Delegated handler: tapping any tier badge anywhere opens the explainer.
    document.addEventListener("click", e => {
      const b = e.target.closest && e.target.closest(".badge[data-tier]");
      if (!b) return;
      const t = b.dataset.tier;
      openModal({
        title: `Data quality: ${t === "stub" ? "no data yet" : t}`,
        bodyHTML: `<p><strong>${esc(TIER_PLAIN[t])}.</strong></p><p>${esc(TIER_INFO[t])}</p>` +
          `<p><a href="sources.html">See where every dataset comes from →</a></p>`,
      });
    });

    // Provenance banner: fixture builds must never pass as real data.
    loadJSON("data/meta.json").then(meta => {
      if (meta.provenance !== "socrata") {
        const b = document.createElement("div");
        b.className = "banner fixtures";
        b.textContent = "Demo build: the data below is SYNTHETIC FIXTURE DATA (provenance: " +
          meta.provenance + "). Run the pipeline against the Chicago Data Portal to publish real data.";
        header.after(b);
      }
    }).catch(() => {});
  }

  window.BSD = {
    TIER_INFO, TIER_PLAIN, DISCLAIMERS, LINKS, FACILITY_COLORS, FACILITY_LABELS,
    SEVERITY_ORDER, SEVERITY_LABELS, SEVERITY_COLORS,
    TREND_LABELS, TREND_ARROWS,
    esc, badge, badgeHTML, noticeHTML, openModal, loadJSON, fmt, qs, setParams,
    downloadCSV, initPage, trendHTML, scoreColor, money,
  };

  if (typeof module !== "undefined" && module.exports) {
    // Pure (DOM-free) helpers only — openModal/badge/initPage are browser-bound.
    module.exports = { trendHTML, scoreColor, money, esc, fmt, badgeHTML, TIER_PLAIN };
  }
})();
